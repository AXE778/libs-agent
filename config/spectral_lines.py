REFERENCE_DIR = os.path.join(DATA_DIR, "reference")
INTENSITY_CSV = os.path.join(REFERENCE_DIR, "intensity.csv")
SENSITIVE_LINE_CSV = os.path.join(REFERENCE_DIR, "sensitive_line.csv")
ELEMENTS_JSON = os.path.join(REFERENCE_DIR, "elements.json")
SPECIES_LIB = os.path.join(REFERENCE_DIR, "SpeciesLib.spe")

PROVENANCE_SOURCE = (
    r"复制自 <LIBS 软件安装目录>\（2026-09-21，sha256 校验一致）"
)

# ---- 仪器波段（你的光谱仪实际覆盖的范围，用来裁掉用不上的谱线）----
BAND_MIN_NM = 180.6
BAND_MAX_NM = 954.0

# ---- 波长匹配容差：按「峰所在处的像素步长」算，不写死 ----
# 一个峰的位置精度不可能好过它占的那个像素。这台仪器像素步长 0.065~0.142 nm，
# 写死 0.05 nm 会让长波端的强线全部匹配不上（实测 O I 777.4 / K I 766.5 都落空）。
TOL_PIXELS = 1.0             # 给 1 个像素的余量
MATCH_TOL_FLOOR_NM = 0.05    # 下限：短波端至少给这么宽
MATCH_TOL_CAP_NM = 0.20      # 上限：再宽窗口里全是候选，就没信息量了

# ---- 电离态：只留 LIBS 里真会出现的 ----
# 常压 LIBS 等离子体温度 ~1 eV，主要是中性原子和一次电离离子；
# 库里一直排到 XLIII（43 价），波段内 IV 及以上的线有 9,222 条，全是干扰。
# （142 条不写电离态的裸符号行实测全是 H，按 H I 处理。）
ION_STATES_KEPT = ("I", "II", "III")

# ---- 谱线库筛选（压歧义的主力）----
# 用 Aki 而不是 intensity：intensity 跨元素不可比，见文件开头那个坑。
# 1e7 是把窗口压到「1 条线 / 1 个元素」的那一档，见上面的表。
LINE_AKI_MIN = 1e7
# 灵敏线无条件保留（它们是人工挑好的分析线，不能被统计门槛删掉）。
ALWAYS_KEEP_SENSITIVE_LINES = True

# ---- 寻峰门槛 ----
PEAK_MIN_SNR = 5.0                    # 峰要高出噪声这么多倍才算真峰
# 峰高还要不低于全谱最强峰的这个比例。
# ★ 2026-09-21 从 0.02 改到 0.002：304 那条 652.38 nm 的饱和线，峰高 57220，
#   而第二强的线只有 647（差 88 倍）。按 2% 卡，整条谱只剩 1 个峰；
#   按 0.2% 卡，能找回 40 个峰。这个门槛的用处只是「别把噪声当峰」，不是选强线。
PEAK_MIN_RATIO_TO_STRONGEST = 0.002
MAX_PEAKS_ANALYZED = 200              # 参与统计的最多多少个峰（多找点，统计更稳）
MAX_PEAKS_REPORT = 40                 # 报给大模型/人的最多多少个峰（控上下文）
# ★ 波段保底配额 —— **只补，不砍**。
# 实测背景：7075 铝合金谱里最强的一批峰全在 766~940 nm，那是空气的
# N I / O I / K I 线（长波端连续背景高、探测器响应也高）；而铝、镁自己的
# 灵敏线在 279~396 nm 的紫外段，谱强弱得多。「全谱取最高 N 个」会让
# 紫外段的金属线拿不到名额。
# 试过「每段只准取 N 个」的硬分层 —— **更差**（316 的 Cr 支持峰从 43 掉到 22），
# 因为紫外段恰好是谱线最密的地方，限名额等于砍真线。
# 所以改成：全局前 N 个照取，*再*把每段最高的几个补进来。
PEAK_STRATIFY_WIDTH_NM = 50.0        # 0 = 关闭保底
PEAK_STRATIFY_MIN_PER_SEGMENT = 3     # 每一段至少保证有几个峰能被看到

# ---- 「算不算有证据」的门槛 ----
# **一个峰对上一条线不算数。** 至少要有这么多条互相独立的峰支持同一元素。
MIN_PEAKS_TO_CLAIM = 2
# 零假设用「置换检验」而不是均匀分布公式：把整组峰整体平移到波段里的
# 随机位置，重新匹配，重复 NULL_SHIFTS 次，看每个元素平均能撞上几个。
# 这样自动带上了谱线在波长上的真实疏密结构，比「均匀分布」假设诚实得多。
NULL_SHIFTS = 200
NULL_SEED = 20260921      # 固定种子 → 同样的输入给同样的数字，可复现
# 尾部概率小于这个值才算「明显超出偶然水平」。
# 200 次置换能把 p 分辨到 1/201 ≈ 0.005，所以 0.01 是能真正达到的门槛。
VERDICT_PVALUE_MAX = 0.01
# 判定用的措辞见 tools/element_analysis.py 的模块说明。

# ---- 灵敏线判定 ----
SENSITIVE_NEAR_NM = 0.05  # 命中的线与该元素公认灵敏线在此距离内 → 算踩在灵敏线上

# ---- 近失配（near miss）诊断 ----
# 一个强峰在容差内只撞到些弱线，但再往外一点点就有一条明显更强的线 ——
# 这种情况要么是波长标定偏了，要么是库里缺线，都值得单独报出来。
# 实测触发场景（2026-09-21）：7075 铝合金谱里 Al I 双线出现在 394.193/395.982，
# 比教科书位置（394.401/396.152）整体偏蓝约 0.19 nm，超出容差被漏掉。
# 这条诊断就是专门用来把这种「差一点点」的峰捞出来的。
NEAR_MISS_SPAN_NM = 0.50     # 在容差之外、这个范围之内找「本该匹配上的那条线」
NEAR_MISS_MIN_AKI = 1e7      # 只把 Aki 够强的线算作「本该匹配上」
# ★ 还要求窗口外那条线比窗口内最强的线**明显更强**，否则不算。
# 实测教训：只按「外面有条强线」判，39/40 个峰都会命中 —— 在 18,039 条线的
# 库里，0.5 nm 内总有一条强线，这条诊断就等于没有筛选力。加上倍数要求后，
# 它才真的只在「本该匹配上却被挤出去」的时候响。
NEAR_MISS_AKI_RATIO = 3.0

# ---- 空气里本来就有的元素 ----
# LIBS 在空气里打，N / O / Ar 的线一定很强（777.4 nm 的 O I 三线组尤其显眼）。
# 它们信号强**不代表样品里含这些元素**，报告里要单独标出来，
# 否则大模型会把「N 有支持」当成样品成分说出来。
AIR_LINE_ELEMENTS = ("N", "O", "Ar")
